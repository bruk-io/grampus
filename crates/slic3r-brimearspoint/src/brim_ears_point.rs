/// `enum class PointsStatus` (`:13-18`): tracks where the current points on a `ModelObject`
/// came from. The vendored enumerators carry no explicit value at all (plain `NoPoints,
/// Generating, AutoGenerated, UserModified`), so their discriminants are the implicit
/// C++ sequence `0, 1, 2, 3` -- Rust's own default (an enum with no `= N` on any variant numbers
/// its variants the same way, starting at `0`), so this is left unannotated rather than writing
/// out `= 0`/`= 1`/`= 2`/`= 3` literals the vendored source itself never writes (which `just
/// port-status` would then have no vendored line to cite for).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum PointsStatus {
    /// No points were generated so far.
    NoPoints,
    /// The autogeneration algorithm triggered, but not yet finished.
    Generating,
    /// Points were autogenerated (i.e. copied from the backend).
    AutoGenerated,
    /// User has done some edits.
    UserModified,
}

