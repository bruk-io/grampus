//! THE COMMITTED EXAMPLE TARGET (task 32-proof-dumps-fuzz, plan step 18, R19). No ported Rust
//! module exists at this step (task 34-foundation-spike's fan-out is where the first one lands,
//! and plan step 20 commits the first truly differential target against it), so this target
//! drives the FFI side alone: it round-trips an arbitrary polygon through
//! `slic3r_ffi::proof::path3_to_paths64` -- `Slic3r::ClipperZUtils::to_paths64`, a pure repack
//! with no arithmetic (`crates/slic3r-ffi/cxx/include_vendored.cpp`'s own module doc) -- and
//! asserts every coordinate comes back unchanged. That is what makes the `cargo-fuzz` crate,
//! its `Arbitrary` implementations and the `just fuzz <target>` recipe real rather than
//! described.
//!
//! THIS TARGET'S NAME: `slic3r-ffi_roundtrip`, at the path `port/port-status`'s
//! `required_fuzz_target_relpath` would derive from a manifest row whose `target crate` is
//! `slic3r-ffi` and `target module` stem is `roundtrip` -- except no `port/manifest.tsv` row
//! ever names `slic3r-ffi` as its `target crate` (it is FFI glue, bound by `29-ffi-bridge-core`,
//! not a ported unit with a crate cut of its own), so this exact path can never collide with a
//! real unit's required target. That is checked, not assumed: this task's pull request body
//! records the grep across the real manifest that confirms it.
//!
//! THE SHAPE A QUALIFYING UNIT'S TARGET FOLLOWS, which this one does not need to (plan step 18):
//! one target per qualifying unit, at `fuzz/fuzz_targets/<crate>_<module>.rs` (the crate and
//! module `port/manifest.tsv`'s row names), generating arbitrary `Point`, `Polygon` and
//! `ExPolygon` inputs -- via newtypes shaped like `ArbPoint`/`ArbPolygon`/`ArbExPolygon` below,
//! converted into *that unit's own ported type* at the target's entry point, never into a
//! `slic3r-ffi` bridge type directly -- and asserting exact equality of integer-coordinate output
//! between the Rust module and the same call through FFI.

#![no_main]

use arbitrary::{Arbitrary, Unstructured};
use libfuzzer_sys::fuzz_target;
use slic3r_ffi::proof::{path3_to_paths64, ProofZPoint};

/// A single point over 64-bit integer coordinates (`coord_t` is `int64_t` at the pin,
/// `vendor/OrcaSlicer/src/libslic3r/libslic3r.h:45-48`). Defined here, inside the fuzz crate,
/// rather than as `impl Arbitrary for` a `slic3r-ffi` bridge type: both the trait
/// (`arbitrary::Arbitrary`) and a bridge type such as `ProofZPoint` are foreign to this crate,
/// which is an orphan-rule error, and no ported `Point` type exists yet for this crate to depend
/// on and implement the trait for instead.
#[derive(Debug, Clone, Copy, Arbitrary)]
struct ArbPoint {
    x: i64,
    y: i64,
}

/// A polygon: at least three points, generated by construction rather than filtered after the
/// fact (a filter-and-retry would waste the fuzzer's entropy budget on inputs it then discards).
#[derive(Debug, Clone)]
struct ArbPolygon {
    points: Vec<ArbPoint>,
}

impl<'a> Arbitrary<'a> for ArbPolygon {
    fn arbitrary(u: &mut Unstructured<'a>) -> arbitrary::Result<Self> {
        let mut points = vec![
            ArbPoint::arbitrary(u)?,
            ArbPoint::arbitrary(u)?,
            ArbPoint::arbitrary(u)?,
        ];
        points.extend(Vec::<ArbPoint>::arbitrary(u)?);
        Ok(ArbPolygon { points })
    }
}

/// A polygon with holes: one contour, zero or more hole polygons, each itself at least three
/// points via [`ArbPolygon`]. Committed for a future target's reuse (plan step 18 names
/// `ExPolygon` inputs as part of the shape every qualifying unit's target follows) -- this
/// branch's own committed target drives the FFI side alone and does not construct one, since no
/// ported module exists yet to take an `ExPolygon`-shaped input.
#[derive(Debug, Clone)]
#[allow(
    dead_code,
    reason = "committed for a future differential target's reuse; unread here"
)]
struct ArbExPolygon {
    contour: ArbPolygon,
    holes: Vec<ArbPolygon>,
}

impl<'a> Arbitrary<'a> for ArbExPolygon {
    fn arbitrary(u: &mut Unstructured<'a>) -> arbitrary::Result<Self> {
        Ok(ArbExPolygon {
            contour: ArbPolygon::arbitrary(u)?,
            holes: Vec::<ArbPolygon>::arbitrary(u)?,
        })
    }
}

fuzz_target!(|polygon: ArbPolygon| {
    // Checked, not only argued by ArbPolygon::arbitrary's construction (which always builds
    // three mandatory points plus an arbitrary tail): a generated polygon must hold at least
    // three points, the task's own "Done when" line.
    assert!(
        polygon.points.len() >= 3,
        "ArbPolygon must generate at least three points"
    );

    let path: Vec<ProofZPoint> = polygon
        .points
        .iter()
        .map(|p| ProofZPoint {
            x: p.x,
            y: p.y,
            z: 0,
        })
        .collect();

    let result = path3_to_paths64(&path);

    let actual: Vec<(i64, i64, i64)> = result.iter().map(|p| (p.x, p.y, p.z)).collect();
    let expected: Vec<(i64, i64, i64)> = path.iter().map(|p| (p.x, p.y, p.z)).collect();
    assert_eq!(
        actual, expected,
        "to_paths64 is a pure repack: every coordinate must come back unchanged"
    );
});
