//! L0 and L1: raw byte identity, and byte identity after the declared normalisation.
//!
//! The normalisation strips exactly the four nondeterministic line kinds that
//! `strip_nondeterministic_gcode_lines` strips in
//! `vendor/OrcaSlicer/tests/fff_print/test_slicing_pipeline_hook.cpp`. `tests/normalisation.rs`
//! pins the four literals below against that vendored function, so this module must define them
//! in exactly one place and nowhere else in the Rust tree.

/// A wall-clock build-attribution comment line, matched by prefix. The literal is the one place
/// in this tree it appears outside `tests/data/` and `tests/normalisation.rs`'s own assertions.
pub const ATTRIBUTION_PREFIX: &[u8] = b"; generated by ";

/// An ObjectID-derived model label, matched by prefix.
pub const MODEL_LABEL_ID_PREFIX: &[u8] = b"; model label id: ";

/// An ObjectID-derived per-object start/stop marker, matched anywhere in the line.
pub const OBJECT_LABEL_ID_SUBSTRING: &[u8] = b"printing object, unique label id: ";

/// The config-dump line naming the hook plugin, matched anywhere in the line.
pub const PIPELINE_PLUGIN_SUBSTRING: &[u8] = b"slicing_pipeline_plugin";

/// Returns `true` when `haystack` contains `needle` anywhere.
fn contains(haystack: &[u8], needle: &[u8]) -> bool {
    if needle.is_empty() {
        return true;
    }
    if haystack.len() < needle.len() {
        return false;
    }
    haystack.windows(needle.len()).any(|w| w == needle)
}

/// Returns `true` when `haystack` starts with `needle`.
fn starts_with(haystack: &[u8], needle: &[u8]) -> bool {
    haystack.len() >= needle.len() && &haystack[..needle.len()] == needle
}

/// Splits `data` the way `std::getline` walks a stream delimited by `\n`: a trailing `\n` ends
/// the final line without producing a phantom empty line after it, a missing trailing `\n` still
/// yields the last partial line, and empty input yields no lines at all.
fn getline_split(data: &[u8]) -> Vec<&[u8]> {
    if data.is_empty() {
        return Vec::new();
    }
    let mut lines: Vec<&[u8]> = data.split(|&b| b == b'\n').collect();
    if data.last() == Some(&b'\n') {
        lines.pop();
    }
    lines
}

/// Applies the declared normalisation: drop the four nondeterministic line kinds, re-emit every
/// kept line followed by `\n`. Never validates UTF-8 — a kept line may hold bytes that are not
/// valid UTF-8.
pub fn normalise(data: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(data.len());
    for line in getline_split(data) {
        if starts_with(line, ATTRIBUTION_PREFIX) {
            continue;
        }
        if starts_with(line, MODEL_LABEL_ID_PREFIX) {
            continue;
        }
        if contains(line, OBJECT_LABEL_ID_SUBSTRING) {
            continue;
        }
        if contains(line, PIPELINE_PLUGIN_SUBSTRING) {
            continue;
        }
        out.extend_from_slice(line);
        out.push(b'\n');
    }
    out
}

/// Where two byte streams first differ, at L0 (a raw byte offset) or at L1 (a one-based line
/// number into each side's normalised stream, with both lines carried for display). A side is
/// `None` when the normalised stream has no line at that number at all (one side is a strict
/// prefix of the other), which must render as distinctly absent — not as an empty line, which a
/// kept-but-blank line also produces.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FailLocation {
    ByteOffset(usize),
    Line {
        number: usize,
        a: Option<Vec<u8>>,
        b: Option<Vec<u8>>,
    },
}

/// The outcome of one level, evaluated independently of every other level.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LevelOutcome {
    Pass,
    Fail(FailLocation),
    NotEvaluated,
}

impl LevelOutcome {
    pub fn is_pass(&self) -> bool {
        matches!(self, LevelOutcome::Pass)
    }
}

/// Byte offset of the first position at which `a` and `b` differ, including a length mismatch
/// (the offset of the end of the shorter side). `None` when the two are identical.
pub(crate) fn first_difference(a: &[u8], b: &[u8]) -> Option<usize> {
    let n = a.len().min(b.len());
    for i in 0..n {
        if a[i] != b[i] {
            return Some(i);
        }
    }
    if a.len() != b.len() {
        return Some(n);
    }
    None
}

/// L0: identical bytes.
pub fn evaluate_l0(a: &[u8], b: &[u8]) -> LevelOutcome {
    match first_difference(a, b) {
        None => LevelOutcome::Pass,
        Some(offset) => LevelOutcome::Fail(FailLocation::ByteOffset(offset)),
    }
}

/// L1: identical bytes after the declared normalisation.
pub fn evaluate_l1(a: &[u8], b: &[u8]) -> LevelOutcome {
    let na = normalise(a);
    let nb = normalise(b);
    if na == nb {
        return LevelOutcome::Pass;
    }
    let lines_a = getline_split(&na);
    let lines_b = getline_split(&nb);
    let n = lines_a.len().max(lines_b.len());
    let diverges_at = (0..n).find(|&i| lines_a.get(i) != lines_b.get(i)).expect(
        "normalise re-emits exactly its kept lines, each followed by one \\n, so \
             getline_split round-trips them: na != nb must show up as an Option-level \
             difference somewhere in 0..n",
    );
    LevelOutcome::Fail(FailLocation::Line {
        number: diverges_at + 1,
        a: lines_a.get(diverges_at).map(|l| l.to_vec()),
        b: lines_b.get(diverges_at).map(|l| l.to_vec()),
    })
}
